    //check user is admin or not
    //hide report and employee buttons if user is not a admin
    public void userMode()
    {
        if(!SessionManager.isAdmin())
        {
            btnEmployees.setVisible(false);
            btnReports.setVisible(false);
        }
        else
        {
            btnEmployees.setVisible(true);
            btnReports.setVisible(true);
        }
    }

    // Switch the page and highlight its menu button.
    public void showPanel(String panelName) {
        java.awt.CardLayout layout = (java.awt.CardLayout) panelContent.getLayout();
        layout.show(panelContent, panelName);

        javax.swing.JButton[] buttons = {
            btnDashboard, btnCustomers, btnPets, btnAppointments,
            btnServices, btnSettings, btnReports, btnEmployees
        };
        String[] names = {
            "dashboard", "customers", "pets", "appointments",
            "services", "settings", "reports", "employees"
        };

        for (int i = 0; i < buttons.length; i++) {
            if (names[i].equals(panelName)) {
                buttons[i].setBackground(java.awt.Color.WHITE);
                buttons[i].setForeground(new java.awt.Color(23, 120, 122));
            } else {
                buttons[i].setBackground(new java.awt.Color(23, 120, 122));
                buttons[i].setForeground(java.awt.Color.WHITE);
            }
        }
        
        
        
    }

