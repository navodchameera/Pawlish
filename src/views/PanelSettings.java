    public PanelSettings()
    {
        initComponents();

        //not connecting controller when opening design view
        if (!java.beans.Beans.isDesignTime())
        {
            ControllerSettings controller = new ControllerSettings(this);

            //loading account when settings opens
            addHierarchyListener(e ->
            {
                if ((e.getChangeFlags() & java.awt.event.HierarchyEvent.SHOWING_CHANGED) != 0)
                {
                    if (isShowing())
                    {
                        controller.refresh();
                    }
                    else
                    {
                        clearPasswords();
                    }
                }
            });
        }
    }

